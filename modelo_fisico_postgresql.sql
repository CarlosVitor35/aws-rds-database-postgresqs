-- 1. CRIAÇÃO DAS TABELAS (DDL)

CREATE TABLE Empresa (
    ID_Empresa INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Razao_Social VARCHAR(200) NOT NULL,
    Nome_Fantasia VARCHAR(200),
    CNPJ VARCHAR(14) NOT NULL UNIQUE,
    Data_Cadastro DATE NOT NULL DEFAULT CURRENT_DATE,
    Status VARCHAR(20) NOT NULL
);

CREATE TABLE Filial (
    ID_Filial INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Empresa INTEGER NOT NULL,
    Razao_Social VARCHAR(200) NOT NULL,
    Nome_Fantasia VARCHAR(200),
    CNPJ VARCHAR(14) NOT NULL UNIQUE,
    Data_Abertura DATE NOT NULL DEFAULT CURRENT_DATE,
    Status VARCHAR(20) NOT NULL,

    CONSTRAINT fk_Empresa
        FOREIGN KEY (ID_Empresa) 
        REFERENCES Empresa(ID_Empresa)
);

CREATE TABLE Cargo (
    ID_Cargo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nome_Cargo VARCHAR(100) NOT NULL,
    Salario DECIMAL(12, 2) NOT NULL,
    
    CONSTRAINT chk_salario_cargo
        CHECK (Salario >= 0)
);

CREATE TABLE Funcionario (
    ID_Funcionario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Filial INTEGER NOT NULL,
    ID_Cargo INTEGER NOT NULL,
    Nome VARCHAR(150) NOT NULL,
    Sobrenome VARCHAR(200) NOT NULL,
    Data_Nascimento DATE NOT NULL,
    CPF VARCHAR(11) NOT NULL UNIQUE,
    E_mail VARCHAR(150) UNIQUE,
    Celular VARCHAR(15) NOT NULL UNIQUE,
    Celular_2 VARCHAR(15) UNIQUE,
    Data_Admissao DATE NOT NULL DEFAULT CURRENT_DATE,
    Status VARCHAR(20) NOT NULL,

    CONSTRAINT fk_Filial
        FOREIGN KEY (ID_Filial) 
        REFERENCES Filial(ID_Filial),

    CONSTRAINT fk_Cargo
        FOREIGN KEY (ID_Cargo) 
        REFERENCES Cargo(ID_Cargo),

    CONSTRAINT chk_data_admissao
        CHECK (Data_Admissao >= Data_Nascimento),

    CONSTRAINT chk_email_funcionario
        CHECK (E_mail IS NULL OR E_mail ~ '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')
);

CREATE TABLE Cliente (
    ID_Cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nome VARCHAR(200) NOT NULL,
    Sobrenome VARCHAR(200) NOT NULL,
    Data_Nascimento DATE NOT NULL,
    CPF VARCHAR(11) UNIQUE NOT NULL,
    Celular VARCHAR(15) NOT NULL UNIQUE,
    Celular_2 VARCHAR(15) UNIQUE,
    E_mail VARCHAR(200) UNIQUE,
    Data_Cadastro DATE NOT NULL DEFAULT CURRENT_DATE,
    Status VARCHAR(20) NOT NULL,

    CONSTRAINT chk_cpf_cliente
        CHECK (CPF ~ '^[0-9]{11}$')
);

CREATE TABLE Endereco (
    ID_Endereco INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Cliente INTEGER,
    ID_Filial INTEGER,
    ID_Empresa INTEGER,
    Logradouro VARCHAR(150) NOT NULL,
    Numero VARCHAR(8) NOT NULL,
    Complemento VARCHAR(50),
    Bairro VARCHAR(80) NOT NULL,
    Cidade VARCHAR(80) NOT NULL,
    Estado VARCHAR(50) NOT NULL,
    CEP VARCHAR(10) NOT NULL,
    
    CONSTRAINT fk_Cliente
        FOREIGN KEY (ID_Cliente)
        REFERENCES Cliente(ID_Cliente),
    
    CONSTRAINT fk_Filial
        FOREIGN KEY (ID_Filial)
        REFERENCES Filial(ID_Filial),

    CONSTRAINT fk_Empresa
        FOREIGN KEY (ID_Empresa) 
        REFERENCES Empresa(ID_Empresa),

    CONSTRAINT chk_endereco_vinculado
        CHECK (num_nonnulls(ID_Cliente, ID_Filial, ID_Empresa) = 1)
);

CREATE TABLE Categoria (
    ID_Categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nome VARCHAR(100) NOT NULL UNIQUE,
    Descricao VARCHAR(300),
    Status VARCHAR(20) NOT NULL,
    Data_Cadastro DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE Estoque (
    ID_Estoque INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Quantidade INTEGER NOT NULL,
    Estoque_Minimo INTEGER NOT NULL,

    CONSTRAINT chk_estoque_quantidade 
        CHECK (Quantidade >= 0 AND Estoque_Minimo >= 0)
);

CREATE TABLE Produto (
    ID_Produto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Categoria INTEGER NOT NULL,
    ID_Estoque INTEGER NOT NULL,
    Nome VARCHAR(150) NOT NULL,
    Descricao VARCHAR(500),
    Preco DECIMAL(12, 2) NOT NULL,
    Data_Cadastro DATE NOT NULL DEFAULT CURRENT_DATE,
    Status VARCHAR(20) NOT NULL,
    Codigo_Barras VARCHAR(50) UNIQUE,

    CONSTRAINT fk_Categoria
        FOREIGN KEY (ID_Categoria)
        REFERENCES Categoria(ID_Categoria),

    CONSTRAINT fk_Estoque
        FOREIGN KEY (ID_Estoque)
        REFERENCES Estoque(ID_Estoque),

    CONSTRAINT uq_produto_estoque 
        UNIQUE (ID_Estoque),

    CONSTRAINT chk_produto_preco 
        CHECK (Preco >= 0)
);

CREATE TABLE Fornecedor (
    ID_Fornecedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Razao_Social VARCHAR(200) NOT NULL,
    Nome_Fantasia VARCHAR(150),
    CNPJ VARCHAR(14) NOT NULL UNIQUE,
    Celular VARCHAR(15) NOT NULL UNIQUE,
    Celular_2 VARCHAR(15) UNIQUE,
    E_mail VARCHAR(200) UNIQUE,
    Data_Cadastro DATE NOT NULL DEFAULT CURRENT_DATE,
    Status VARCHAR(20) NOT NULL,

    CONSTRAINT chk_celular_fornecedor
        CHECK (Celular ~ '^[0-9]{10,11}$' AND (Celular_2 IS NULL OR Celular_2 ~ '^[0-9]{10,11}$'))
);

CREATE TABLE Fornecedor_Produto (
    ID_Fornecedor INTEGER NOT NULL,
    ID_Produto INTEGER NOT NULL,

    PRIMARY KEY (ID_Fornecedor, ID_Produto),

    CONSTRAINT fk_Fornecedor
        FOREIGN KEY (ID_Fornecedor) 
        REFERENCES Fornecedor(ID_Fornecedor),
    
    CONSTRAINT fk_Produto
        FOREIGN KEY (ID_Produto) 
        REFERENCES Produto(ID_Produto)    
);

CREATE TABLE Pagamento (
    ID_Pagamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Forma_Pagamento VARCHAR(30) NOT NULL,
    Valor DECIMAL(12, 2) NOT NULL,
    Data_Pagamento DATE NOT NULL DEFAULT CURRENT_DATE,
    Status VARCHAR(20) NOT NULL,

    CONSTRAINT chk_valor_pagamento 
        CHECK (Valor >= 0)
);

CREATE TABLE Pedido (
    ID_Pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Endereco INTEGER NOT NULL,
    ID_Cliente INTEGER NOT NULL,
    ID_Funcionario INTEGER NOT NULL,
    ID_Pagamento INTEGER NOT NULL,
    ID_Filial INTEGER NOT NULL,
    Valor_Total DECIMAL(12, 2) NOT NULL,
    Status VARCHAR(30) NOT NULL,
    Data_Pedido DATE NOT NULL DEFAULT CURRENT_DATE,
    Observacao VARCHAR(500),

    CONSTRAINT fk_Endereco
        FOREIGN KEY (ID_Endereco)
        REFERENCES Endereco(ID_Endereco),

    CONSTRAINT fk_Cliente
        FOREIGN KEY (ID_Cliente)
        REFERENCES Cliente(ID_Cliente),

    CONSTRAINT fk_Funcionario
        FOREIGN KEY (ID_Funcionario)
        REFERENCES Funcionario(ID_Funcionario),

    CONSTRAINT fk_Pagamento
        FOREIGN KEY (ID_Pagamento)
        REFERENCES Pagamento(ID_Pagamento),

    CONSTRAINT fk_Filial
        FOREIGN KEY (ID_Filial)
        REFERENCES Filial(ID_Filial),

    CONSTRAINT chk_valor_total_pedido
        CHECK (Valor_Total >= 0)
);

CREATE TABLE Itens_Pedido (
    ID_Item INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Pedido INTEGER NOT NULL,
    ID_Produto INTEGER NOT NULL,
    Quantidade INTEGER NOT NULL,
    Preco_Unico DECIMAL(12, 2) NOT NULL,

    CONSTRAINT fk_Pedido
        FOREIGN KEY (ID_Pedido)
        REFERENCES Pedido(ID_Pedido), 

    CONSTRAINT fk_Produto
        FOREIGN KEY (ID_Produto)
        REFERENCES Produto(ID_Produto),

    CONSTRAINT chk_quantidade_item
        CHECK (Quantidade > 0 AND Preco_Unico >= 0)
);

CREATE TABLE Movimentacao_Estoque (
    ID_Movimentacao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Estoque INTEGER NOT NULL,
    ID_Produto INTEGER NOT NULL,
    Tipo VARCHAR(20) NOT NULL,
    Quantidade INTEGER NOT NULL,
    Data_Movimentacao DATE NOT NULL DEFAULT CURRENT_DATE,
    Observacao VARCHAR(300),

    CONSTRAINT fk_Estoque
        FOREIGN KEY (ID_Estoque)
        REFERENCES Estoque(ID_Estoque),

    CONSTRAINT fk_Produto
        FOREIGN KEY (ID_Produto)
        REFERENCES Produto(ID_Produto),

    CONSTRAINT chk_quantidade_movimentacao
        CHECK (Quantidade > 0),

    CONSTRAINT chk_tipo_movimentacao
        CHECK (Tipo IN ('Entrada', 'Saída'))
);


